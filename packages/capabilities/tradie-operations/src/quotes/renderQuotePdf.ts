import { eq } from "drizzle-orm";
import { buildStructuredPdfBytes } from "@kaesava/core/pdf";
import { uploadObjectToStorage } from "@kaesava/core";
import { fileNotes, tmQuotes, type DbOrTx } from "@kaesava/db/rings/tradie-matters";

export interface RenderQuotePdfParams {
  tenantId: string;
  appId: string;
  userId: string;
  quoteId: string;
  quoteNumber: string;
  title: string;
  customerName: string;
  abn: string | null;
  gstMode: string;
  subtotalExTax: string;
  totalTax: string;
  totalIncTax: string;
  depositAmountDue: string;
  lines: Array<{
    description: string;
    quantity: string;
    unitSellPrice: string;
    lineTotalIncTax: string;
  }>;
}

function buildQuotePdfBytes(p: RenderQuotePdfParams): Uint8Array {
  return buildStructuredPdfBytes({
    title: `Quote ${p.quoteNumber}`,
    headerRight: p.abn ? `ABN ${p.abn}` : undefined,
    metaLines: [
      `Title: ${p.title}`,
      `Customer: ${p.customerName}`,
      `GST Mode: ${p.gstMode}`,
    ],
    columns: [
      { label: "Description", width: 270, align: "left" },
      { label: "Qty", width: 65, align: "right" },
      { label: "Unit", width: 85, align: "right" },
      { label: "Total", width: 95, align: "right" },
    ],
    rows: p.lines.map((l) => [l.description, l.quantity, l.unitSellPrice, l.lineTotalIncTax]),
    totalsLines: [
      `Subtotal (ex GST): ${p.subtotalExTax}`,
      `GST: ${p.totalTax}`,
      `Total (inc GST): ${p.totalIncTax}`,
      ...(Number(p.depositAmountDue) > 0 ? [`Deposit Required: ${p.depositAmountDue}`] : []),
    ],
  });
}

export async function renderQuotePdf(
  db: DbOrTx,
  params: RenderQuotePdfParams
): Promise<{ fileNoteId: string; fileKey: string }> {
  const pdfBytes = buildQuotePdfBytes(params);
  const fileName = `quote-${params.quoteNumber}.pdf`;
  const fileKey = `apps/${params.appId}/tenants/${params.tenantId}/quote/${params.quoteId}/${crypto.randomUUID()}-${fileName}`;
  await uploadObjectToStorage(fileKey, pdfBytes, "application/pdf");

  const now = new Date();
  const [note] = await db
    .insert(fileNotes)
    .values({
      id: crypto.randomUUID(),
      tenantId: params.tenantId,
      appId: params.appId,
      entityType: "QUOTE",
      entityId: params.quoteId,
      comment: `Generated quote PDF ${params.quoteNumber}`,
      fileKey,
      fileName,
      fileMimeType: "application/pdf",
      fileSize: String(pdfBytes.byteLength),
      isPrivate: false,
      isAutoGenerated: true,
      userId: null,
      createdAt: now,
      createdBy: params.userId,
      updatedAt: now,
      updatedBy: params.userId,
    })
    .returning({ id: fileNotes.id });

  await db
    .update(tmQuotes)
    .set({ pdfFileNoteId: note.id, updatedAt: now, updatedBy: params.userId })
    .where(eq(tmQuotes.id, params.quoteId));

  return { fileNoteId: note.id, fileKey };
}

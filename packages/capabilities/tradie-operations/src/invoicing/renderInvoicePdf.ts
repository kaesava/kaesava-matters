import { eq } from "drizzle-orm";
import { buildStructuredPdfBytes } from "@kaesava/core/pdf";
import { uploadObjectToStorage } from "@kaesava/core";
import { fileNotes, tmInvoices, type DbOrTx } from "@kaesava/db/rings/tradie-matters";

export interface RenderInvoicePdfParams {
  tenantId: string;
  appId: string;
  userId: string;
  invoiceId: string;
  invoiceNumber: string;
  documentTitle: string;
  customerName: string;
  abn: string | null;
  businessName?: string | null;
  buyerAbn?: string | null;
  payIdType?: string | null;
  payIdValue?: string | null;
  bankAccountName?: string | null;
  bankBsb?: string | null;
  bankAccountNumber?: string | null;
  gstRegistered: boolean;
  issueDate: string;
  dueDate: string;
  subtotalExTax: string;
  totalTax: string;
  totalIncTax: string;
  balanceDue: string;
  lines: Array<{
    description: string;
    quantity: string;
    unitSellPrice: string;
    lineTotalIncTax: string;
  }>;
}

function buildInvoicePdfBytes(p: RenderInvoicePdfParams): Uint8Array {
  return buildStructuredPdfBytes({
    title: `${p.documentTitle} ${p.invoiceNumber}`,
    headerRight: [p.businessName, p.abn ? `ABN ${p.abn}` : null].filter(Boolean).join(" | ") || undefined,
    metaLines: [
      `Customer: ${p.customerName}${p.buyerAbn ? ` (ABN ${p.buyerAbn})` : ""}`,
      `Issue Date: ${p.issueDate}   Due Date: ${p.dueDate}`,
      ...(p.gstRegistered ? [] : ["No GST has been charged"]),
      ...(p.payIdValue ? [`PayID (${p.payIdType ?? "ID"}): ${p.payIdValue}`] : []),
      ...(p.bankBsb && p.bankAccountNumber
        ? [`Bank: ${p.bankAccountName ?? p.businessName ?? ""} BSB ${p.bankBsb} Acc ${p.bankAccountNumber} Ref ${p.invoiceNumber}`]
        : []),
    ],
    columns: [
      { label: "Description", width: 270, align: "left" },
      { label: "Qty", width: 65, align: "right" },
      { label: "Unit", width: 85, align: "right" },
      { label: "Total", width: 95, align: "right" },
    ],
    rows: p.lines.map((l) => [l.description, l.quantity, l.unitSellPrice, l.lineTotalIncTax]),
    totalsLines: [
      `Subtotal (ex GST): ${p.subtotalExTax}`,
      `GST: ${p.totalTax}`,
      `Total: ${p.totalIncTax}`,
      `Balance Due: ${p.balanceDue}`,
    ],
  });
}

export async function renderInvoicePdf(
  db: DbOrTx,
  params: RenderInvoicePdfParams
): Promise<{ fileNoteId: string; fileKey: string }> {
  const pdfBytes = buildInvoicePdfBytes(params);
  const fileName = `invoice-${params.invoiceNumber}.pdf`;
  const fileKey = `apps/${params.appId}/tenants/${params.tenantId}/invoice/${params.invoiceId}/${crypto.randomUUID()}-${fileName}`;
  await uploadObjectToStorage(fileKey, pdfBytes, "application/pdf");

  const now = new Date();
  const [note] = await db
    .insert(fileNotes)
    .values({
      id: crypto.randomUUID(),
      tenantId: params.tenantId,
      appId: params.appId,
      entityType: "INVOICE",
      entityId: params.invoiceId,
      comment: `Generated ${params.documentTitle} PDF ${params.invoiceNumber}`,
      fileKey,
      fileName,
      fileMimeType: "application/pdf",
      fileSize: String(pdfBytes.byteLength),
      isPrivate: false,
      isAutoGenerated: true,
      userId: null,
      createdAt: now,
      createdBy: params.userId,
      updatedAt: now,
      updatedBy: params.userId,
    })
    .returning({ id: fileNotes.id });

  await db
    .update(tmInvoices)
    .set({ pdfFileNoteId: note.id, updatedAt: now, updatedBy: params.userId })
    .where(eq(tmInvoices.id, params.invoiceId));

  return { fileNoteId: note.id, fileKey };
}
